// ─── Helper Functions ─────────────────────────────

/**
 * Get a single article by its slug.
 * Returns undefined if not found.
 */
export function getArticleBySlug(slug) {
  return articles.find((a) => a.slug === slug);
}

/**
 * Get all articles that belong to a given category.
 * Case-insensitive match.
 */
export function getArticlesByCategory(category) {
  return articles.filter(
    (a) => a.category.toLowerCase() === category.toLowerCase()
  );
}

/**
 * Get all articles that include a given tag.
 * Case-insensitive match.
 */
export function getArticlesByTag(tag) {
  return articles.filter((a) =>
    a.tags.some((t) => t.toLowerCase() === tag.toLowerCase())
  );
}

/**
 * Get featured articles only.
 * Pass a limit to cap the number returned.
 */
export function getFeaturedArticles(limit = articles.length) {
  return articles.filter((a) => a.featured).slice(0, limit);
}

/**
 * Get all unique categories, sorted alphabetically.
 */
export function getAllCategories() {
  const cats = articles.map((a) => a.category);
  return [...new Set(cats)].sort();
}

/**
 * Get all unique tags, sorted alphabetically.
 */
export function getAllTags() {
  const tags = articles.flatMap((a) => a.tags);
  return [...new Set(tags)].sort();
}

/**
 * Sort articles by date, newest first.
 */
export function getSortedArticles() {
  return [...articles].sort((a, b) => new Date(b.date) - new Date(a.date));
}

/**
 * Get related articles: same category, excluding the current article.
 * Pass a limit (default 3).
 */
export function getRelatedArticles(currentSlug, limit = 3) {
  const current = getArticleBySlug(currentSlug);
  if (!current) return [];
  return articles
    .filter(
      (a) =>
        a.slug !== currentSlug &&
        a.category === current.category
    )
    .slice(0, limit);
}
